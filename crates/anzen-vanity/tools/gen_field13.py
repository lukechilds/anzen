#!/usr/bin/env python3
"""Generate the unrolled 13-bit-limb field functions in src/field13.wgsl.

Apple's Metal compiler keeps loop-indexed arrays in memory: the same field code written as loops
ran at 0.43x of the 32-bit version, and 2.3x faster than it once every index was a constant. This
writes those functions straight-line between the GENERATED markers. Run it after changing the
representation:

    crates/anzen-vanity/tools/gen_field13.py
"""

import os
from pathlib import Path

FILE = Path(__file__).resolve().parents[1] / "src" / "field13.wgsl"
BEGIN = "// BEGIN GENERATED by tools/gen_field13.py; edit the generator, not this block.\n"
END = "// END GENERATED\n"
LIMBS = 20


def carry_chain(name: str, count: int) -> list[str]:
    """Carry limbs 0..count of `name` into the next; leaves the final carry in v >> 13."""
    lines = [f"    v = {name}[0]; {name}[0] = v & LIMB_MASK;"]
    for i in range(1, count):
        lines.append(f"    v = {name}[{i}] + (v >> 13u); {name}[{i}] = v & LIMB_MASK;")
    return lines


def normalize_light() -> list[str]:
    """One carry chain, one fold and a short tail: enough for sums of normalized limbs (below
    2^15), whose carry out of limb 19 is at most 3. Checked by a model of these exact u32
    operations over 600k random and edge inputs."""
    lines = [
        "// Normalize limbs below 2^15 (sums and differences of normalized elements): one carry",
        "// chain, then the fold of at most a few times 2^260 only reaches limbs 0..3.",
        "fn f_normalize_light(a: F) -> F {",
        "    var r = a;",
        "    var v: u32;",
    ]
    lines += carry_chain("r", LIMBS)
    lines += [
        "    let carry = v >> 13u;",
        "    r[0] += carry * 15632u;",
        "    r[2] += carry * 1024u;",
        "    r[1] += r[0] >> 13u;",
        "    r[0] &= LIMB_MASK;",
        "    r[2] += r[1] >> 13u;",
        "    r[1] &= LIMB_MASK;",
        "    r[3] += r[2] >> 13u;",
        "    r[2] &= LIMB_MASK;",
        "    return r;",
        "}",
        "",
    ]
    return lines


def limbwise(name: str, params: str, expression: str, comment: str) -> list[str]:
    lines = [comment, f"fn {name}({params}) -> F {{", "    var r: F;"]
    lines += [f"    r[{i}] = {expression.format(i=i)};" for i in range(LIMBS)]
    lines += ["    return f_normalize_light(r);", "}", ""]
    return lines


def reduce() -> list[str]:
    lines = [
        "// Reduce a product's 39 column sums (each below 2^31) to a normalized element, folding",
        "// with 2^260 ≡ 2^36 + 15632 (mod p).",
        "fn f_reduce(c: array<u32, 39>) -> F {",
        "    // Carry only the columns of weight 2^260 and up, which the fold multiplies. The low",
        "    // columns stay sums below 2^30.4, below 2^31 with the folded terms, and the next chain",
        "    // carries them.",
        "    var l: array<u32, 40>;",
        "    var v: u32;",
        "    v = c[20]; l[20] = v & LIMB_MASK;",
    ]
    for k in range(21, 39):
        lines.append(f"    v = c[{k}] + (v >> 13u); l[{k}] = v & LIMB_MASK;")
    lines += [
        "    l[39] = v >> 13u;",
        "    // Limb i + 20 (weight 2^260 and up) adds 15632× at limb i and 2^10× at limb i + 2.",
        "    var r: array<u32, 22>;",
    ]
    for i in range(22):
        terms = []
        if i < LIMBS:
            terms.append(f"c[{i}] + l[{20 + i}] * 15632u")
        if i >= 2:
            terms.append(f"l[{18 + i}] * 1024u")
        lines.append(f"    r[{i}] = " + " + ".join(terms) + ";")
    lines += carry_chain("r", 22)
    lines += [
        "    let carry = v >> 13u;",
        "    // r[20] + r[21]·2^13 + carry·2^26 sit at weight 2^260: fold them once more.",
        "    var out: F;",
    ]
    lines += [f"    out[{i}] = r[{i}];" for i in range(LIMBS)]
    lines += [
        "    out[0] += r[20] * 15632u;",
        "    out[2] += r[20] * 1024u;",
        "    out[1] += r[21] * 15632u;",
        "    out[3] += r[21] * 1024u;",
        "    out[2] += carry * 15632u;",
        "    out[4] += carry * 1024u;",
        "    // Only limbs 0..4 exceed 13 bits, so a tail to limb 6 leaves limb 6 at most 2^13 and",
        "    // the rest below it. tools/model_reduce.py checks these exact u32 operations.",
    ]
    for i in range(6):
        lines += [f"    out[{i + 1}] += out[{i}] >> 13u;", f"    out[{i}] &= LIMB_MASK;"]
    lines += [
        "    return out;",
        "}",
        "",
    ]
    return lines


HALF = LIMBS // 2


def columns(prefix: str, a: str, b: str, square: bool) -> list[str]:
    """`let` bindings for the 19 column sums of a 10-limb product (or square) of expressions."""
    lines = []
    for k in range(2 * HALF - 1):
        if square:
            cross = [f"{a(i)} * {a(k - i)}" for i in range(HALF) if i < k - i < HALF]
            parts = ["(" + " + ".join(cross) + ") * 2u"] if cross else []
            if k % 2 == 0:
                parts.append(f"{a(k // 2)} * {a(k // 2)}")
        else:
            parts = [f"{a(i)} * {b(k - i)}" for i in range(HALF) if 0 <= k - i < HALF]
        lines.append(f"    let {prefix}{k} = " + " + ".join(parts) + ";")
    return lines


def columns_karatsuba(prefix: str, a, b, square: bool) -> list[str]:
    """`let` bindings for the 19 columns of a 10-limb product of normalized limbs (below 2^13)
    through a second Karatsuba level on 5-limb halves, whose sums stay below 2^14."""
    q = HALF // 2
    lines = [f"    let {prefix}s{i} = {a(i)} + {a(i + q)};" for i in range(q)]
    if not square:
        lines += [f"    let {prefix}t{i} = {b(i)} + {b(i + q)};" for i in range(q)]
    def sub(name, x, y):
        out = []
        for k in range(2 * q - 1):
            if square:
                cross = [f"{x(i)} * {x(k - i)}" for i in range(q) if i < k - i < q]
                parts = ["(" + " + ".join(cross) + ") * 2u"] if cross else []
                if k % 2 == 0:
                    parts.append(f"{x(k // 2)} * {x(k // 2)}")
            else:
                parts = [f"{x(i)} * {y(k - i)}" for i in range(q) if 0 <= k - i < q]
            out.append(f"    let {prefix}{name}{k} = " + " + ".join(parts) + ";")
        return out
    lines += sub("ll", lambda i: a(i), lambda i: b(i) if b else None)
    lines += sub("hh", lambda i: a(i + q), lambda i: b(i + q) if b else None)
    lines += sub("mm", lambda i: f"{prefix}s{i}", lambda i: f"{prefix}t{i}")
    for k in range(2 * HALF - 1):
        terms = []
        if k <= 2 * q - 2:
            terms.append(f"{prefix}ll{k}")
        if q <= k <= 3 * q - 2:
            m = k - q
            terms.append(f"({prefix}mm{m} - {prefix}ll{m} - {prefix}hh{m})")
        if 2 * q <= k:
            terms.append(f"{prefix}hh{k - 2 * q}")
        lines.append(f"    let {prefix}{k} = " + " + ".join(terms) + ";")
    return lines


# Karatsuba levels in f_mul and f_sqr: 2 (the default) or 1, from KARATSUBA_LEVELS.
LEVELS = int(os.environ.get("KARATSUBA_LEVELS", "2"))


def karatsuba(square: bool) -> list[str]:
    """One level of Karatsuba on the two 10-limb halves: low·low, high·high and
    (low + high)·(low + high), whose middle columns less the other two are the cross terms.
    Half sums are below 2^14, so their products are below 2^28 and a 10-term column below 2^32;
    every column difference is exact because the cross terms are non-negative."""
    lines = []
    if square:
        lines += [f"    let s{i} = a[{i}] + a[{i + HALF}];" for i in range(HALF)]
        halves = columns_karatsuba if LEVELS == 2 else columns
        lines += halves("lo", lambda i: f"a[{i}]", None, True)
        lines += halves("hi", lambda i: f"a[{i + HALF}]", None, True)
        lines += columns("mid", lambda i: f"s{i}", None, True)
    else:
        lines += [f"    let s{i} = a[{i}] + a[{i + HALF}];" for i in range(HALF)]
        lines += [f"    let t{i} = b[{i}] + b[{i + HALF}];" for i in range(HALF)]
        halves = columns_karatsuba if LEVELS == 2 else columns
        lines += halves("lo", lambda i: f"a[{i}]", lambda i: f"b[{i}]", False)
        lines += halves("hi", lambda i: f"a[{i + HALF}]", lambda i: f"b[{i + HALF}]", False)
        lines += columns("mid", lambda i: f"s{i}", lambda i: f"t{i}", False)
    for k in range(2 * LIMBS - 1):
        terms = []
        if k <= 2 * HALF - 2:
            terms.append(f"lo{k}")
        if HALF <= k <= 3 * HALF - 2:
            m = k - HALF
            terms.append(f"(mid{m} - lo{m} - hi{m})")
        if 2 * HALF <= k:
            terms.append(f"hi{k - 2 * HALF}")
        lines.append(f"    c[{k}] = " + " + ".join(terms) + ";")
    return lines


def multiply() -> list[str]:
    lines = [
        "// 300 limb products instead of 400 (one level of Karatsuba).",
        "fn f_mul(a: F, b: F) -> F {",
        "    var c: array<u32, 39>;",
    ]
    lines += karatsuba(square=False)
    lines += ["    return f_reduce(c);", "}", ""]
    return lines


def square() -> list[str]:
    lines = [
        "// 165 limb products instead of 210 (one level of Karatsuba on top of doubled cross products).",
        "fn f_sqr(a: F) -> F {",
        "    var c: array<u32, 39>;",
    ]
    lines += karatsuba(square=True)
    lines += ["    return f_reduce(c);", "}", ""]
    return lines


def main() -> None:
    block = []
    block += normalize_light()
    block += limbwise("f_add", "a: F, b: F", "a[{i}] + b[{i}]", "// a + b.")
    block += limbwise("f_sub", "a: F, b: F", "a[{i}] + P13_TIMES_32[{i}] - b[{i}]", "// a − b, as a + 32p − b.")
    block += limbwise("f_neg", "a: F", "P13_TIMES_32[{i}] - a[{i}]", "// −a, as 32p − a.")
    # Fused forms for the mixed addition: one normalization where chained adds and subtracts
    # would take two or three. Limbs stay below 2^17, and tools/model_light.py checks the light
    # normalization keeps them at or below 2^13.
    block += limbwise("f_times4", "a: F", "a[{i}] * 4u", "// 4a.")
    block += limbwise(
        "f_double_sub", "a: F, b: F", "(a[{i}] + P13_TIMES_32[{i}] - b[{i}]) * 2u", "// 2(a − b), as 2(a + 32p − b)."
    )
    block += limbwise(
        "f_sub_double",
        "a: F, b: F",
        "a[{i}] + P13_TIMES_32[{i}] * 2u - b[{i}] * 2u",
        "// a − 2b, as a + 64p − 2b.",
    )
    block += limbwise(
        "f_sub_sub_double",
        "a: F, b: F, c: F",
        "a[{i}] + P13_TIMES_32[{i}] * 2u - b[{i}] - c[{i}] * 2u",
        "// a − b − 2c, as a + 64p − b − 2c.",
    )
    block += reduce()
    block += multiply()
    block += square()
    source = FILE.read_text()
    start = source.index(BEGIN) + len(BEGIN)
    end = source.index(END)
    FILE.write_text(source[:start] + "\n".join(block) + source[end:])


if __name__ == "__main__":
    main()
